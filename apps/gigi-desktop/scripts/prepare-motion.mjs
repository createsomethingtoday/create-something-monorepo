import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

/** Package the official self-contained distribution without a runtime loader or network. */
export async function prepareMotion({ outputRoot = app, check = false } = {}) {
  const manifest = JSON.parse(await readFile(join(app, 'package.json'), 'utf8'));
  const packagePath = require.resolve('gsap/package.json');
  const installed = JSON.parse(await readFile(packagePath, 'utf8'));
  if (manifest.dependencies?.gsap !== installed.version || !/^\d+\.\d+\.\d+$/.test(manifest.dependencies.gsap)) {
    throw new Error('GSAP must be installed at the exact version pinned by the desktop app.');
  }
  const source = await readFile(join(dirname(packagePath), 'dist', 'gsap.min.js'), 'utf8');
  const banner = source.match(/^\/\*![\s\S]*?\*\//)?.[0];
  if (!banner || !banner.includes(`GSAP ${installed.version}`) || !banner.includes('https://gsap.com/standard-license')) {
    throw new Error('The GSAP distribution is missing its expected version and license notice.');
  }
  const digest = createHash('sha256').update(source).digest('hex');
  const code = `/* GiGi local GSAP vendor. Generated by scripts/prepare-motion.mjs.\n * Source: gsap@${installed.version}/dist/gsap.min.js (includes CSSPlugin).\n * Upstream source SHA-256: ${digest}\n * Terms: https://gsap.com/standard-license\n */\nconst gsapModule = { exports: {} };\n(function(module, exports) {\n${source}\n})(gsapModule, gsapModule.exports);\nexport const gsap = gsapModule.exports.gsap;\n`;
  const notice = `GSAP ${installed.version}\n\nBundled file: web/vendor/gsap.mjs\nUpstream distribution: gsap@${installed.version}/dist/gsap.min.js, including CSSPlugin\nUpstream source SHA-256: ${digest}\nSource: https://www.npmjs.com/package/gsap/v/${installed.version}\nProject: https://gsap.com/\nLicense declaration: ${installed.license}\nCanonical terms: https://gsap.com/community/standard-license/\n\nThe pinned npm package does not include a standalone LICENSE file. Its complete\nshipped license banner is retained below and unchanged within the vendor bundle.\nThe standard license permits commercial digital-interface implementations and\nrestricts competing no-code visual animation builders. GiGi uses GSAP to animate\nits own onboarding; it does not expose an animation-building tool. The canonical\nlicense terms govern; this notice is an attribution and scope record.\n\n${banner}\n`;
  const vendorPath = join(outputRoot, 'web', 'vendor', 'gsap.mjs');
  const noticePath = join(outputRoot, 'third-party', 'GSAP-NOTICE.txt');
  for (const [path, expected] of [[vendorPath, code], [noticePath, notice]]) {
    if (check) {
      const actual = await readFile(path, 'utf8').catch(() => null);
      if (actual !== expected) throw new Error('The GSAP motion vendor or notice is missing or stale. Run pnpm prepare:motion.');
    } else {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, expected);
    }
  }
  return { vendorPath, noticePath, version: installed.version, bytes: Buffer.byteLength(code), sourceSha256: digest };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(value => value !== '--check')) throw new Error('Use prepare-motion.mjs [--check].');
  const result = await prepareMotion({ check: process.argv.includes('--check') });
  process.stdout.write(`GSAP ${result.version} local vendor ${process.argv.includes('--check') ? 'verified' : 'prepared'} (${result.bytes} bytes).\n`);
}
