import { readFileSync, writeFileSync } from 'node:fs';

const registryUrl = new URL('../../../config/mcp-hub/registry.json', import.meta.url);
const outputUrl = new URL('../src/lib/data/integrationCatalog.generated.ts', import.meta.url);
const checkOnly = process.argv.includes('--check');

const registry = JSON.parse(readFileSync(registryUrl, 'utf8'));
const descriptionPrefix = 'Composio toolkit gateway:';

const integrations = Object.entries(registry.servers)
  .filter(([, server]) => String(server.description ?? '').startsWith(descriptionPrefix))
  .map(([id, server]) => {
    const description = String(server.description);
    const match = description.match(/^Composio toolkit gateway: (.+) \(([^)]+)\) - /);

    if (!match) {
      throw new Error(`Unable to parse public connector metadata for ${id}`);
    }

    return {
      id,
      name: match[1],
      slug: match[2],
      status: 'connector_available'
    };
  })
  .sort((left, right) => left.name.localeCompare(right.name, 'en'));

const serialized = `${[
  '// This file is generated by scripts/generate-integration-catalog.mjs.',
  '// It intentionally contains only public-safe brokered connector metadata.',
  `export const integrationCatalogSourceVersion = ${JSON.stringify(registry.version)} as const;`,
  `export const connectorCatalogCount = ${integrations.length} as const;`,
  'export const integrationCatalog = [',
  ...integrations.map((integration) => `  ${JSON.stringify(integration)},`),
  '] as const;',
  '',
  "export type IntegrationCatalogEntry = (typeof integrationCatalog)[number];",
  ''
].join('\n')}`;

if (checkOnly) {
  let current = '';
  try {
    current = readFileSync(outputUrl, 'utf8');
  } catch {
    // A missing generated file is reported as drift below.
  }

  if (current !== serialized) {
    console.error('Integration catalog is out of date. Run pnpm integrations:generate.');
    process.exit(1);
  }

  console.log(`Integration catalog is current (${integrations.length} brokered connectors).`);
} else {
  writeFileSync(outputUrl, serialized);
  console.log(`Generated ${integrations.length} public brokered connectors.`);
}
