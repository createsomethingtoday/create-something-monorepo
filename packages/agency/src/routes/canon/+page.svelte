          <p>
            We kept the felt. It let us draw two things with thread. A seam could hold a work coat
            together, and a row of stitches could draw a smile.
          </p>
          <p>
            The face kept its digital rhythm. Cream stitches make the oval eyes and the little
            smile. Around them, the head has rounded edges, visible fibers and enough depth to feel
            like an object on a bench.
          </p>
