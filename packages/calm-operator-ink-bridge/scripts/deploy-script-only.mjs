#!/usr/bin/env node

import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(scriptDir, '..');
const workspaceRoot = path.resolve(packageRoot, '..', '..');
const sourceConfigPath = path.join(packageRoot, 'wrangler.toml');
const generatedConfigPath = path.join(packageRoot, '.wrangler.script-only.generated.toml');
const runWranglerPath = path.join(workspaceRoot, 'scripts', 'run-wrangler.mjs');

function removeRoutes(toml) {
  const output = [];
  let skippingRoute = false;

  for (const line of toml.split(/\r?\n/)) {
    if (/^\s*\[\[routes\]\]\s*$/.test(line)) {
      skippingRoute = true;
      continue;
    }

    if (skippingRoute && /^\s*\[/.test(line)) {
      skippingRoute = false;
    }

    if (!skippingRoute) output.push(line);
  }

  return output.join('\n').trimEnd() + '\n';
}

const sourceConfig = fs.readFileSync(sourceConfigPath, 'utf8');
const generatedConfig = [
  '# Generated by scripts/deploy-script-only.mjs. Do not edit.',
  '# Routes are intentionally omitted so normal script deploys do not need route-edit permission.',
  removeRoutes(sourceConfig)
].join('\n');

fs.writeFileSync(generatedConfigPath, generatedConfig);

const forwardedArgs = process.argv.slice(2);
if (forwardedArgs[0] === '--') forwardedArgs.shift();

const child = spawn(
  process.execPath,
  [runWranglerPath, 'deploy', '-c', generatedConfigPath, ...forwardedArgs],
  {
    cwd: packageRoot,
    stdio: 'inherit'
  }
);

child.on('exit', (code, signal) => {
  if (signal) {
    process.kill(process.pid, signal);
    return;
  }

  process.exit(code ?? 1);
});
