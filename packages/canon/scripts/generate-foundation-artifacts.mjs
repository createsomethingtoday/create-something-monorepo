/** Bounded artifact generation. Reads Canon CSS; writes only Canon/portable tokens. */
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const base=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const css=readFileSync(resolve(base,'src/lib/styles/tokens.css'),'utf8');
const root=css.match(/:root\s*{([\s\S]*?)\n}/)[1];
const parse=s=>Object.fromEntries([...s.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map(m=>[m[1],m[2].trim()]));
const all=parse(root);
const tokens=Object.fromEntries(Object.entries(all).filter(([k])=>k.includes('-performance')));
const compatibilityAliases=Object.fromEntries(Object.entries(all).filter(([k,v])=>!k.includes('-performance')&&/^var\(--[^)]*performance/.test(v)).map(([k,v])=>[k,v.slice(4,-1)]));
const theme=selector=>parse(css.slice(css.indexOf(selector)).match(/\{([\s\S]*?)\n}/)[1]);
const themes={light:theme("[data-theme='light']"),dark:theme("[data-theme='dark']")};
const contract={source:'packages/canon/src/lib/styles/tokens.css',tokens,compatibilityAliases};
function tokenName(path){const parts=path.flatMap(x=>x.replace(/[A-Z]/g,m=>'-'+m.toLowerCase()).split('-'));return '--'+parts[0]+'-performance-'+parts.slice(1).join('-');}
function updateTree(node,path=[]){
 if(!node||typeof node!=='object')return;
 if('$value' in node||'value' in node){const key=node.cssVar??tokenName(path);const value=all[key];if(value!==undefined){node['$value' in node?'$value':'value']=value;if('$description' in node)delete node.$description;if('description' in node)delete node.description;}return;}
 for(const [key,value] of Object.entries(node))updateTree(value,[...path,key]);
}
for(const file of ['tokens.dtcg.json','tokens.figma.json','canon.json']){
 const path=resolve(base,'src/lib/styles',file);const data=JSON.parse(readFileSync(path,'utf8'));
 if(file==='tokens.dtcg.json'){for(const [k,v] of Object.entries(data))if(!k.startsWith('$')&&k!=='performanceContract')updateTree(v,[k]);data.$extensions['com.createsomething'].themes=themes;}
 if(file==='tokens.figma.json'){updateTree(data.core);for(const [name,values] of Object.entries(themes))data['themes/'+name]=values;delete data['themes/high-contrast'];}
 if(file==='canon.json'){updateTree(data);data.themes=themes;}
 data.performanceContract=contract;data.foundationThemes=themes;
 writeFileSync(path,JSON.stringify(data,null,2)+'\n');
}
const portablePath=resolve(base,'../canon-tokens/tokens.json');const portable=JSON.parse(readFileSync(portablePath,'utf8'));
function updatePortable(node,path=[]){for(const [k,v] of Object.entries(node)){if(v&&typeof v==='object')updatePortable(v,[...path,k]);else{let p=[...path,k];if(p[0]==='typography'){p[0]=({fontFamily:'font',fontSize:'text',lineHeight:'leading',fontWeight:'font',letterSpacing:'tracking'})[p[1]]??p[1];p.splice(1,1);}if(p[0]==='animation')p.shift();const value=all[tokenName(p)];if(value!==undefined)node[k]=value;}}}
updatePortable(portable);portable.performanceContract=contract;portable.foundationThemes=themes;writeFileSync(portablePath,JSON.stringify(portable,null,2)+'\n');
writeFileSync(resolve(base,'../canon-tokens/tokens.css'),css);
const scss='// Generated by generate-foundation-artifacts.mjs. Canon CSS owns values.\n'+Object.entries(all).map(([k,v])=>`$${k.slice(2)}: ${v};`).join('\n')+'\n\n'+css;
for(const path of ['src/lib/styles/tokens.scss','../canon-tokens/tokens.scss'])writeFileSync(resolve(base,path),scss);
console.log('Generated Canon and portable artifacts only.');
