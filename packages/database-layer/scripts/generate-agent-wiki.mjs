function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function rel(filePath) {
  return path.relative(packageRoot, filePath).split(path.sep).join('/');
}

function relFromWiki(filePath) {
  return path.relative(outputDir, filePath).split(path.sep).join('/');
}

function markdownLink(label, target) {
  return `[${label}](${target})`;
}

function displayPath(record) {
  return String(record?.path ?? '').trim() || record?.title || record?.id || '.';
}

function countBy(items, key) {
  const counts = new Map();
  for (const item of items) {
    const value = item[key] ?? 'unknown';
    counts.set(value, (counts.get(value) ?? 0) + 1);
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));
}

function sanitizeCell(value) {
  return String(value ?? '')
    .replace(/\r?\n/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();
}

function table(headers, rows) {
  return [
    `| ${headers.map(sanitizeCell).join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(sanitizeCell).join(' | ')} |`)
  ].join('\n');
}

function list(items) {
  if (items.length === 0) return '- None';
  return items.map((item) => `- ${item}`).join('\n');
}

function page(title, body) {
  return `# ${title}

> Generated by \`pnpm --filter @create-something/database-layer agent-wiki:generate\`.
> Treat this wiki as an agent-readable projection. The JSON artifacts named on each page remain the source of truth.

${body.trim()}
`;
}

function topNodes(nodes, predicate, limit = 8) {
  return nodes
    .filter(predicate)
    .sort((a, b) => a.path.localeCompare(b.path) || a.id.localeCompare(b.id))
    .slice(0, limit);
}

function sourceArtifactTable() {
  return table(
    ['Artifact', 'Purpose'],
    [
      [markdownLink(rel(paths.topology), relFromWiki(paths.topology)), 'Canonical repo-derived Substrate topology records and graph edges.'],
      [markdownLink(rel(paths.topology3d), relFromWiki(paths.topology3d)), '3D projection, lenses, and topology context API metadata.'],
      [markdownLink(rel(paths.management), relFromWiki(paths.management)), 'API/MCP/agent management resources and operations.'],
      [markdownLink(rel(paths.businessRecommendations), relFromWiki(paths.businessRecommendations)), 'Operationalized business recommendations with lanes, receipts, and approval boundaries.'],
      [markdownLink(rel(paths.organizationReview), relFromWiki(paths.organizationReview)), 'Business-health readout tied to topology diagnostics and operating slices.'],
      [markdownLink(rel(paths.diagnostics), relFromWiki(paths.diagnostics)), 'Generated topology health signals and review cues.'],
      [markdownLink(rel(paths.operatingSliceReview), relFromWiki(paths.operatingSliceReview)), 'Review-ready operating slices with evidence paths and promotion boundaries.'],
      [markdownLink(rel(paths.operatingSliceReadiness), relFromWiki(paths.operatingSliceReadiness)), 'Local readiness gates for every operating slice.'],
      [markdownLink(rel(paths.atlasSession), relFromWiki(paths.atlasSession)), 'Exported Atlas Studio canvas and story projection for the topology.']
    ]
  );
}

function surfaceRows(topology) {
  return countBy(topology.nodes, 'surface').map(([surface, count]) => {
    const records = topNodes(topology.nodes, (node) => node.surface === surface, 4);
    return [
      surface,
      count,
      records.map((record) => `${displayPath(record)} (${record.tier})`).join('; ')
    ];
  });
}

function readinessRows(readiness) {
  return readiness.items
    .slice()
    .sort((a, b) => b.recordCount - a.recordCount || a.title.localeCompare(b.title))
    .map((item) => [
      item.title,
      item.tier,
      item.surface,
      item.recordCount,
      item.productionStatus,
      countBy(item.gates ?? [], 'status').map(([status, count]) => `${status}: ${count}`).join(', ')
    ]);
}

function operationRows(management) {
  return management.operations
    .slice()
    .sort((a, b) => a.apiPath.localeCompare(b.apiPath) || a.id.localeCompare(b.id))
    .map((operation) => [
      operation.apiMethod,
      operation.apiPath,
      operation.mcpTool,
      operation.agentCommand,
      operation.requiresApproval ? 'yes' : 'no'
    ]);
}

