function operatingSlicesPage(state) {
  const { review, readiness } = state;
  const readinessBySlice = new Map(readiness.items.map((item) => [item.sliceId, item]));
  const sliceRows = review.slices
    .slice()
    .sort((a, b) => {
      const aItem = readinessBySlice.get(a.id);
      const bItem = readinessBySlice.get(b.id);
      return (bItem?.recordCount ?? 0) - (aItem?.recordCount ?? 0) || a.title.localeCompare(b.title);
    })
    .map((slice) => {
      const item = readinessBySlice.get(slice.id);
      return [
        slice.title,
        slice.tier,
        slice.surface,
        slice.status,
        item?.productionStatus,
        item?.recordCount ?? slice.recordIds?.length ?? 0,
        (slice.validationCommands ?? []).join('; ')
      ];
    });
  const promotionBoundaries = [...new Set(review.slices.map((slice) => slice.promotionBoundary).filter(Boolean))];

  return page(
    'Operating Slices',
    `
Operating slices turn mapped topology coverage into review-ready work packets.
They are not production approval; they are the local bridge between "mapped" and
"ready to promote through the owning workflow."

## Readiness Summary

${table(['Title', 'Tier', 'Surface', 'Records', 'Production status', 'Gate status counts'], readinessRows(readiness))}

## Review Slices

${table(['Title', 'Tier', 'Surface', 'Status', 'Production status', 'Records', 'Validation'], sliceRows)}

## Promotion Boundary

${list(promotionBoundaries)}
`
  );
}

