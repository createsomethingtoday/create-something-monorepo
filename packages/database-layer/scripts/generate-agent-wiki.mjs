function existingMarkdownFiles() {
  if (!fs.existsSync(outputDir)) return [];
  return fs
    .readdirSync(outputDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => entry.name)
    .sort();
}

const stale = [];
const expectedFiles = new Set(files.keys());
const unexpectedFiles = existingMarkdownFiles().filter((fileName) => !expectedFiles.has(fileName));

for (const fileName of unexpectedFiles) {
  stale.push(rel(path.join(outputDir, fileName)));
  if (!check) fs.unlinkSync(path.join(outputDir, fileName));
}

for (const [fileName, content] of files) {
  const filePath = path.join(outputDir, fileName);
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current !== content) {
    stale.push(rel(filePath));
    if (!check) {
      fs.mkdirSync(path.dirname(filePath), { recursive: true });
      fs.writeFileSync(filePath, content);
    }
  }
}

if (check && stale.length > 0) {
  console.error(`Agent wiki is stale. Regenerate with: pnpm --filter @create-something/database-layer agent-wiki:generate`);
  for (const file of stale) console.error(`- ${file}`);
  process.exit(1);
}

console.log(
  check
    ? `Agent wiki is current (${files.size} files).`
    : `Generated Atlas/Substrate agent wiki (${files.size} files) in ${rel(outputDir)}.`
);
