import fs from 'node:fs';
import path from 'node:path';

const packageRoot = path.resolve(new URL('..', import.meta.url).pathname);
const outputPath = path.join(packageRoot, 'worker', 'generated-state.mjs');

function readJson(name) {
  return JSON.parse(fs.readFileSync(path.join(packageRoot, 'data', name), 'utf8'));
}

const state = {
  managementSurface: readJson('create-something-management-surface.json'),
  operatingSliceReview: readJson('create-something-operating-slice-review.json'),
  operatingSliceReadiness: readJson('create-something-operating-slice-readiness.json'),
  topology: readJson('create-something-internal-topology.json'),
  atlasSession: readJson('create-something-internal-operating-topology.atlas-session.json'),
  clientOverlayCoverage: readJson('create-something-client-overlay-coverage.json'),
  agentConfigCoverage: readJson('create-something-agent-config-coverage.json'),
  runtimeBindingCoverage: readJson('create-something-runtime-binding-coverage.json'),
  topologyDiagnostics: readJson('create-something-topology-diagnostics.json'),
  performanceContract: readJson('create-something-performance-contract.json'),
  organizationReview: readJson('create-something-organization-review.json'),
  businessRecommendations: readJson('create-something-business-operating-recommendations.json')
};

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  `${outputPath}.tmp`,
  [
    '// Generated by scripts/generate-worker-state.mjs. Do not edit by hand.',
    'export const databaseLayerWorkerState = ',
    JSON.stringify(state, null, 2),
    ';',
    ''
  ].join('\n')
);
fs.renameSync(`${outputPath}.tmp`, outputPath);

console.log(
  JSON.stringify(
    {
      outputPath: path.relative(packageRoot, outputPath),
      topologyNodes: state.topology.nodes.length,
      slices: state.operatingSliceReview.slices.length,
      readinessItems: state.operatingSliceReadiness.items.length,
      clientOverlays: state.clientOverlayCoverage.overlays.length,
      managementResources: state.managementSurface.resources.length,
      diagnosticsValueState: state.topologyDiagnostics.summary.valueState,
      performanceBudgets: state.performanceContract.budgets.length,
      organizationValueState: state.organizationReview.valueState,
      businessRecommendationLanes: state.businessRecommendations.lanes.length
    },
    null,
    2
  )
);
