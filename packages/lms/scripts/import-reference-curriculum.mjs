/**
 * Import the English lesson narratives from a local checkout of
 * rohitg00/ai-engineering-from-scratch. Keep the upstream license and an exact
 * revision so every page can link to its runnable source.
 *
 * Usage: node scripts/import-reference-curriculum.mjs /path/to/ai-engineering-from-scratch
 */
import { readFile, readdir, mkdir, copyFile, writeFile, rm, stat, mkdtemp, rename } from 'node:fs/promises';
import { join, resolve, relative } from 'node:path';
import { execFileSync } from 'node:child_process';
import { runInNewContext } from 'node:vm';
import { randomUUID } from 'node:crypto';

const upstream = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('Pass the local upstream checkout path.');
const root = resolve(import.meta.dirname, '..');
const referenceRoot = join(root, 'src/lib/content/reference');
const figureRoot = join(root, 'static/reference-figures');
const revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' }).trim();
const sourceRoot = join(upstream, 'phases');
const phases = (await readdir(sourceRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const stagedReference = await mkdtemp(join(root, 'src/lib/content/.reference-import-'));
const stagedFigures = await mkdtemp(join(root, 'static/.reference-figures-import-'));
const stagedPublicLicense = join(root, 'static', `.reference-license-import-${randomUUID()}.txt`);
const swaps = [];

async function swapDirectory(staged, target) {
  const backup = `${target}.import-backup-${randomUUID()}`;
  let hadPrevious = false;
  try {
    await rename(target, backup);
    hadPrevious = true;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  try {
    await rename(staged, target);
  } catch (error) {
    if (hadPrevious) await rename(backup, target);
    throw error;
  }
  return { target, backup: hadPrevious ? backup : null };
}

try {
  const catalog = [];
  for (const phase of phases) {
    const phaseRoot = join(sourceRoot, phase);
    const lessons = (await readdir(phaseRoot, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();
    for (const lesson of lessons) {
      const source = join(phaseRoot, lesson, 'docs/en.md');
      let markdown;
      try {
        markdown = await readFile(source, 'utf8');
      } catch {
        continue;
      }
      const targetDir = join(stagedReference, 'phases', phase, lesson);
      await mkdir(targetDir, { recursive: true });
      await writeFile(join(targetDir, 'en.md'), markdown.replace(/[\t ]+$/gm, ''));
      const title = markdown.match(/^#\s+(.+)$/m)?.[1]?.trim() ?? lesson.replace(/^\d+-/, '').replaceAll('-', ' ');
      const time = markdown.match(/^\*\*Time:\*\*\s*(.+)$/m)?.[1]?.trim() ?? 'Self-paced';
      const hasCode = await stat(join(phaseRoot, lesson, 'code')).then((value) => value.isDirectory()).catch(() => false);
      catalog.push({ phase, lesson, title, time, hasCode });
    }
  }

  if (catalog.length !== 523) {
    throw new Error(`Expected 523 English lesson documents; found ${catalog.length}. Existing snapshot preserved.`);
  }
  await copyFile(join(referenceRoot, 'index.ts'), join(stagedReference, 'index.ts'));
  await copyFile(join(upstream, 'LICENSE'), join(stagedReference, 'LICENSE.upstream'));
  await copyFile(join(upstream, 'LICENSE'), stagedPublicLicense);
  await writeFile(
    join(stagedReference, 'catalog.generated.ts'),
    `/* Generated by scripts/import-reference-curriculum.mjs from ${revision}. */\n` +
      `export const REFERENCE_REVISION = ${JSON.stringify(revision)};\n` +
      `export const REFERENCE_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n`
  );

  // The lesson narratives use `figure` fences for interactive diagrams.
  // Build and stage the figure providers before replacing any checked-in data.
  execFileSync('node', ['site/build.js'], { cwd: upstream, stdio: 'pipe' });
  const siteRoot = join(upstream, 'site');
  const sandbox = { window: {} };
  runInNewContext(await readFile(join(siteRoot, 'figure-manifest.js'), 'utf8'), sandbox);
  const prefix = '/reference-figures/';
  const order = Array.from(sandbox.window.AIFS_FIGURE_PROVIDER_ORDER);
  const routes = Object.fromEntries(Object.entries(sandbox.window.AIFS_FIGURE_PROVIDERS).map(([id, providers]) => [id, Array.from(providers, (provider) => prefix + provider)]));
  const versions = Object.fromEntries(Object.entries(sandbox.window.AIFS_FIGURE_PROVIDER_VERSIONS).map(([provider, version]) => [prefix + provider, version]));
  await copyFile(join(siteRoot, 'lesson-figures.js'), join(stagedFigures, 'lesson-figures.js'));
  for (const provider of order) await copyFile(join(siteRoot, provider), join(stagedFigures, provider));
  await writeFile(join(stagedFigures, 'figure-manifest.js'),
    `// AI Engineering from Scratch figure routing at ${revision}.\n` +
    `window.AIFS_FIGURE_PROVIDER_ORDER = ${JSON.stringify(order.map((provider) => prefix + provider))};\n` +
    `window.AIFS_FIGURE_PROVIDER_VERSIONS = ${JSON.stringify(versions)};\n` +
    `window.AIFS_FIGURE_PROVIDERS = ${JSON.stringify(routes)};\n`
  );

  swaps.push(await swapDirectory(stagedReference, referenceRoot));
  swaps.push(await swapDirectory(stagedFigures, figureRoot));
  await rename(stagedPublicLicense, join(root, 'static/reference-license.txt'));
  for (const { backup } of swaps) {
    if (backup) await rm(backup, { recursive: true, force: true })
      .catch((error) => console.warn(`Imported successfully; backup cleanup needs attention: ${error.message}`));
  }
  console.log(`Imported ${catalog.length} lessons and ${order.length} figure providers from ${relative(root, upstream)} at ${revision}.`);
} catch (error) {
  for (const { target, backup } of swaps.reverse()) {
    await rm(target, { recursive: true, force: true });
    if (backup) await rename(backup, target);
  }
  throw error;
} finally {
  await rm(stagedReference, { recursive: true, force: true });
  await rm(stagedFigures, { recursive: true, force: true });
  await rm(stagedPublicLicense, { force: true });
}
