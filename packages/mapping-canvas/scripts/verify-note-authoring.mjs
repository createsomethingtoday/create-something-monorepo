import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
const output = new URL('../output/playwright/note-authoring/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome' });
const results = [];
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, acceptDownloads: true });
    await context.addInitScript(() => { window.__tools = {}; Object.defineProperty(document, 'modelContext', { configurable: true, value: { registerTool(tool) { window.__tools[tool.name] = tool; } } }); });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const call = (name, input = {}) => page.evaluate(({ name, input }) => window.__tools[name].execute(input), { name, input });
    await page.goto(process.env.CANVAS_URL || 'http://127.0.0.1:5187', { waitUntil: 'networkidle' });
    await page.waitForFunction(() => Boolean(window.__tools.draw_compose));
    await page.getByRole('button', { name: 'Start sketching', exact: true }).click();
    const created = await call('draw_compose', { nodes: [{ ref: 'decision', text: 'Release decision\nShip the desktop app with readable notes.\nCheck signing and saved documents.' }], placement: 'visible-center' });
    const id = created.refs.decision;
    await call('draw_select', { ids: [id] });
    await page.screenshot({ path: new URL(`plain-${width}.png`, output).pathname });
    await page.getByRole('button', { name: 'Edit & format', exact: true }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByLabel('Block 1 style', { exact: true }).selectOption('heading1');
    await page.getByLabel('Block 3 style', { exact: true }).selectOption('bullet');
    const body = page.getByLabel('Block 2 text', { exact: true });
    await body.focus();
    await body.evaluate(field => { field.setSelectionRange(5, 20); field.dispatchEvent(new Event('select')); });
    await page.getByRole('button', { name: 'Bold', exact: true }).click();
    await expect(page.locator('.preview .bold')).toHaveText('the desktop app');
    await page.screenshot({ path: new URL(`editor-${width}.png`, output).pathname });
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    const state = () => call('draw_get_state');
    const saved = (await state()).document.objects.find(object => object.id === id);
    expect(saved.content.blocks.map(block => block.type)).toEqual(['heading1', 'paragraph', 'bullet']);
    expect(saved.content.blocks[1].runs.some(run => run.bold && run.text === 'the desktop app')).toBe(true);
    await expect(page.locator(`[data-object-id="${id}"] h1`)).toHaveText('Release decision');
    await page.screenshot({ path: new URL(`formatted-${width}.png`, output).pathname });
    await page.locator('.file-menu summary').click();
    for (const extension of ['json', 'svg', 'png']) {
      const pending = page.waitForEvent('download');
      await page.getByRole('button', { name: extension.toUpperCase(), exact: true }).click();
      await (await pending).saveAs(new URL(`mixed-${width}.${extension}`, output).pathname);
    }
    await page.locator('.file-menu summary').click();
    const mixedSvg = await readFile(new URL(`mixed-${width}.svg`, output), 'utf8');
    expect(mixedSvg).toContain('font-weight="700"');
    expect(mixedSvg).toContain('Release decision');
    const mixedPage = await context.newPage();
    await mixedPage.setContent(mixedSvg);
    await mixedPage.screenshot({ path: new URL(`mixed-export-svg-${width}.png`, output).pathname });
    await mixedPage.setContent(`<img style="max-width:100%" src="data:image/png;base64,${(await readFile(new URL(`mixed-${width}.png`, output))).toString('base64')}" />`);
    await expect(mixedPage.locator('img')).toBeVisible();
    await mixedPage.screenshot({ path: new URL(`mixed-export-png-${width}.png`, output).pathname });
    await mixedPage.close();
    await page.getByRole('button', { name: 'Undo', exact: true }).click();
    expect((await state()).document.objects.find(object => object.id === id).content).toBeUndefined();
    await page.getByRole('button', { name: 'Redo', exact: true }).click();
    expect((await state()).document.objects.find(object => object.id === id).content).toEqual(saved.content);
    await call('draw_select', { ids: [id] });
    await page.getByRole('button', { name: 'Edit & format', exact: true }).click();
    await page.getByLabel('Block 2 text', { exact: true }).fill('Ship the desktop app with readable notes and keyboard controls.');
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    const amended = (await state()).document.objects.find(object => object.id === id);
    expect(amended.content.blocks[1].runs.find(run => run.bold)?.text).toBe('the desktop app');
    await page.getByRole('button', { name: 'Edit & format', exact: true }).click();
    const typed = ' Sequential typing stays bounded.'.repeat(8);
    const typingField = page.getByLabel('Block 2 text', { exact: true });
    await typingField.focus();
    await typingField.evaluate(field => field.setSelectionRange(field.value.length, field.value.length));
    await typingField.pressSequentially(typed);
    await page.getByRole('button', { name: 'Save note', exact: true }).click();
    const sequential = (await state()).document.objects.find(object => object.id === id);
    expect(sequential.content.blocks[1].runs).toHaveLength(3);
    expect(sequential.content.blocks[1].runs.find(run => run.bold)?.text).toBe('the desktop app');
    expect(sequential.text).toContain(typed);
    await page.getByRole('button', { name: 'Edit & format', exact: true }).click();
    await page.getByLabel('Block 1 text', { exact: true }).fill('Discard this draft');
    await page.keyboard.press('Escape');
    expect((await state()).document.objects.find(object => object.id === id)).toEqual(sequential);
    await page.getByRole('button', { name: 'Edit & format', exact: true }).click();
    await page.getByLabel('Block 2 text', { exact: true }).fill('Long note '.repeat(80) + 'averylongunbrokenword'.repeat(10));
    await page.screenshot({ path: new URL(`long-editor-${width}.png`, output).pathname });
    await page.keyboard.press('Control+Enter');
    await page.waitForTimeout(400);
    await page.reload({ waitUntil: 'networkidle' });
    await page.waitForFunction(() => Boolean(window.__tools.draw_get_state));
    const reloaded = (await state()).document.objects.find(object => object.id === id);
    expect(reloaded.content.blocks[0].type).toBe('heading1');
    expect(reloaded.text).toContain('averylongunbrokenword');
    await expect(page.locator(`[data-object-id="${id}"] .rich-note`)).toBeVisible();
    expect(reloaded.height).toBeGreaterThan(500);
    await page.getByRole('button', { name: 'Fit drawing', exact: true }).click();
    await page.screenshot({ path: new URL(`long-canvas-${width}.png`, output).pathname });
    await page.locator('.file-menu summary').click();
    for (const extension of ['json', 'svg', 'png']) {
      const downloadEvent = page.waitForEvent('download');
      await page.getByRole('button', { name: extension.toUpperCase(), exact: true }).click();
      const download = await downloadEvent;
      await download.saveAs(new URL(`note-${width}.${extension}`, output).pathname);
    }
    const json = JSON.parse(await readFile(new URL(`note-${width}.json`, output), 'utf8'));
    expect(json.objects.find(object => object.id === id).content).toEqual(reloaded.content);
    const svg = await readFile(new URL(`note-${width}.svg`, output), 'utf8');
    expect(svg).toContain('Release decision'); expect(svg).toContain('averylongunbrokenword'); expect(svg).not.toContain('foreignObject');
    const exported = await context.newPage();
    await exported.setContent(svg);
    await exported.screenshot({ path: new URL(`export-svg-${width}.png`, output).pathname });
    await exported.setContent(`<img style="max-width:100%" src="data:image/png;base64,${(await readFile(new URL(`note-${width}.png`, output))).toString('base64')}" />`);
    await expect(exported.locator('img')).toBeVisible();
    expect(await exported.locator('img').evaluate(image => image.naturalHeight)).toBeGreaterThan(500);
    await exported.screenshot({ path: new URL(`export-png-${width}.png`, output).pathname });
    await exported.close();
    expect(errors).toEqual([]);
    results.push({ width, passed: true, checks: ['mixed blocks', 'selected emphasis', 'edit existing rich note', 'sequential typing', 'undo/redo', 'cancel', 'long text', 'reload', 'JSON/SVG/PNG exports'], errors });
    await context.close();
  }
  await writeFile(new URL('report.json', output), JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results));
} finally { await browser.close(); }
