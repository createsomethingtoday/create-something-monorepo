#!/usr/bin/env python3
"""Build a public-safe synthetic fixture; never consume the reference recording.

Run from any directory with the kit's pinned Python environment:
  .venv/bin/python scripts/production_demo.py
The complete static release is .release-demo/dist. The generated authoring
manifest is also a safe candidate for the repository's default example.
"""
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

from PIL import Image, ImageDraw
import imageio_ffmpeg

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ('index.html', 'player.js', 'style.css', 'render.py', 'requirements.txt',
         'build.mjs', 'serve.mjs', 'hosting-headers.mjs', 'package.json')


def generate():
    lock = ROOT / '.production-demo.lock'
    try:
        lock.mkdir()
    except FileExistsError:
        raise RuntimeError(f'Demo generation is already running; inspect an interrupted run before removing {lock}')
    transaction = Path(tempfile.mkdtemp(prefix='.release-demo-build-', dir=ROOT))
    candidate = transaction / 'candidate'
    backup = transaction / 'previous'
    target = ROOT / '.release-demo'
    preserve_backup = False
    try:
        candidate.mkdir()
        for name in TOOLS:
            shutil.copy2(ROOT / name, candidate / name)
        spec = importlib.util.spec_from_file_location('demo_render', ROOT / 'render.py')
        renderer = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(renderer)
        ff = os.environ.get('FFMPEG') or shutil.which('ffmpeg') or imageio_ffmpeg.get_ffmpeg_exe()
        beats = [
            ('01 / PLAN', '12 seconds', 'Three scenes. One manifest.', 'Set the viewer outcome.'),
            ('02 / INSPECT', '0 → 4 → 8', 'Exact chapter starts, in seconds.', 'Keep guidance on the timeline.'),
            ('03 / VERIFY', '360 frames', '12 seconds × 30 frames per second.', 'Check the exported artifact.'),
        ]
        for i, (label, value, detail, action) in enumerate(beats):
            frame = Image.new('RGB', (1280, 720), '#090909')
            draw = ImageDraw.Draw(frame)
            draw.text((352, 74), 'SYNTHETIC / TOOLING DEMO', font=renderer.font(23, True), fill='#b6b6ae')
            draw.line((352, 120, 928, 120), fill='#343434', width=2)
            draw.text((352, 166), label, font=renderer.font(42, True), fill='#f3f3f0')
            draw.text((352, 260), value, font=renderer.font(76, True), fill='#f3f3f0')
            draw.text((352, 374), detail, font=renderer.font(27), fill='#f3f3f0')
            draw.text((352, 430), action, font=renderer.font(27), fill='#b6b6ae')
            draw.text((352, 577), 'Generated example. No live workflow.', font=renderer.font(24), fill='#b6b6ae')
            draw.line((352, 630, 928, 630), fill='#343434', width=2)
            frame.save(candidate / f'scene-{i}.png')
        source = candidate / 'synthetic-source.mp4'
        renderer.run([ff, '-y', '-framerate', '1/4', '-start_number', '0', '-i', str(candidate/'scene-%d.png'),
                      '-t', '12', '-r', '30', '-c:v', 'libx264', '-threads', '1', '-crf', '18',
                      '-pix_fmt', 'yuv420p', '-fflags', '+bitexact', '-flags:v', '+bitexact',
                      '-map_metadata', '-1', '-movflags', '+faststart', str(source)])
        renderer.verify_frame_count(ff, source, 360)
        copy = [
            ('plan', 'Plan', 'Define the outcome.', 'Start with a clear viewer outcome.', 'Synthetic example: three scenes across 12 seconds.'),
            ('inspect', 'Inspect', 'Inspect the timing.', 'Seek a chapter and watch its guidance update.', 'The example starts chapters at 0, 4, and 8 seconds.'),
            ('verify', 'Verify', 'Verify the export.', 'Check playback and the exported artifact.', 'This synthetic fixture contains 360 frames at 30 fps.'),
        ]
        manifest = {
            'version': 1,
            'title': 'Walkthrough tooling · synthetic demo',
            'description': 'A generated, silent example of synchronized guidance. It does not depict a real app, customer, or live operation.',
            'source': {'file': 'screen.mp4', 'original': source.name,
                       'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                       'duration': 12, 'in': 0, 'out': 12, 'crop': [1280, 720, 0, 0],
                       'credit': 'Synthetic demonstration · no live workflow',
                       'attribution': 'Generated by CREATE SOMETHING to demonstrate the player and renderer; no customer recording.'},
            'scenes': [{'id': beat[0], 'start': i*4, 'end': (i+1)*4, 'label': beat[1],
                        'title': beat[2], 'prompt': beat[3], 'evidence': beat[4]} for i, beat in enumerate(copy)],
            'mobile': {'file': 'screen-mobile.mp4', 'poster': 'poster-mobile.jpg', 'width': 720, 'height': 720,
                       'shots': [{'start': i*4, 'end': (i+1)*4, 'crop': [640, 640, 320, 40],
                                  'label': 'Synthetic '+beat[1].lower()} for i, beat in enumerate(copy)]},
        }
        manifest_path = candidate/'manifest.json'
        manifest_path.write_text(json.dumps(manifest, indent=2)+'\n')
        renderer.build(manifest_path)
        for name in ['screen.mp4', 'walkthrough.mp4', 'screen-mobile.mp4', 'walkthrough-mobile.mp4']:
            renderer.verify_frame_count(ff, candidate/name, 360)
        subprocess.run(['node', str(candidate/'build.mjs')], check=True)
        if target.exists():
            if not target.is_dir() or target.is_symlink():
                raise RuntimeError('The release demo target must be a regular directory.')
            os.replace(target, backup)
        try:
            os.replace(candidate, target)
        except BaseException:
            if backup.exists():
                try:
                    os.replace(backup, target)
                except OSError:
                    preserve_backup = True
                    raise RuntimeError(f'Release demo rollback failed; recover {backup}')
            raise
        print(json.dumps({'directory': str(target), 'dist': str(target/'dist'),
                          'manifest': str(target/'manifest.json'), 'synthetic': True,
                          'source_sha256': manifest['source']['sha256'], 'frames': 360,
                          'duration_seconds': 12, 'published': False}, indent=2))
    finally:
        if not preserve_backup:
            shutil.rmtree(transaction)
        lock.rmdir()


if __name__ == '__main__':
    generate()
